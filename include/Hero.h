// Защита от повторного включения заголовочного файла
// Если HERO_H не определен, то определяем его и включаем содержимое файла
// Это предотвращает ошибки компиляции при множественном включении одного файла
#ifndef HERO_H
#define HERO_H

// Подключаем базовый класс, от которого наследуется Hero
#include "Base.h"
// Подключаем стандартную библиотеку для работы со строками
#include <string>
// Подключаем стандартный контейнер vector для динамического массива навыков
#include <vector>

// Класс Hero, наследуется от абстрактного класса Base
// public наследование означает, что Hero является типом Base
class Hero : public Base {
private:
    // Приватные поля класса - инкапсуляция данных
    
    // Имя героя
    std::string name;
    // Тип оружия героя (меч, лук, посох и т.д.)
    std::string weaponType;
    // Динамический массив навыков героя
    // vector используется для хранения произвольного количества строк
    std::vector<std::string> skills;

public:
    // === КОНСТРУКТОРЫ И ДЕСТРУКТОР ===
    
    // Конструктор по умолчанию - создает героя с базовыми значениями
    Hero();
    
    // Конструктор с параметрами - создает героя с заданными именем и оружием
    // const std::string& - передача по константной ссыле для избежания копирования
    Hero(const std::string& name, const std::string& weapon);
    
    // Конструктор копирования - создает копию существующего героя
    // Нужен для правильного копирования объектов (правило трех в C++)
    Hero(const Hero& other);
    
    // Деструктор - освобождает ресурсы при удалении объекта
    // override указывает, что это переопределение виртуального метода базового класса
    ~Hero() override;

    // === SET/GET МЕТОДЫ (геттеры и сеттеры) ===
    // Обеспечивают контролируемый доступ к приватным полям
    
    // Установка имени героя (реализация чисто виртуального метода из Base)
    void setName(const std::string& name) override;
    
    // Получение имени героя (реализация чисто виртуального метода из Base)
    std::string getName() const override;
    
    // Установка типа оружия
    void setWeaponType(const std::string& weapon);
    
    // Получение типа оружия
    std::string getWeaponType() const;
    
    // Добавление нового навыка в конец массива skills
    void addSkill(const std::string& skill);
    
    // Удаление навыка по индексу из массива skills
    // Может выбрасывать исключение при неверном индексе
    void removeSkill(int index);

    // === РЕАЛИЗАЦИЯ ВИРТУАЛЬНЫХ МЕТОДОВ БАЗОВОГО КЛАССА ===
    // Эти методы должны быть реализованы, так как они чисто виртуальные в Base
    
    // Вывод информации о герое в консоль
    // const в конце означает, что метод не изменяет состояние объекта
    void print() const override;
    
    // Сохранение данных героя в файл
    // ofstream& out - выходной файловый поток, передается по ссылке
    void saveToFile(std::ofstream& out) const override;
    
    // Загрузка данных героя из файла
    // ifstream& in - входной файловый поток, передается по ссылке
    void loadFromFile(std::ifstream& in) override;

    // === ПЕРЕГРУЗКА ОПЕРАТОРОВ ===
    
    // Перегрузка оператора присваивания
    // Обеспечивает корректное присваивание объектов Hero
    // Возвращает ссылку на текущий объект для возможности цепочки присваиваний
    Hero& operator=(const Hero& other);
};

// Завершение блока защиты от повторного включения
#endif
